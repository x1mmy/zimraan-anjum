/**
 * Bakes the ZA monogram from the Danfo outlines into plain SVG path data.
 *
 * Why bake rather than set live text in Danfo: an SVG favicon cannot load a
 * webfont, so a `<text>` mark would silently fall back to whatever the browser
 * had lying around. Converting the glyphs to paths once means the favicon, the
 * Apple touch icon and the nav mark are all the exact same geometry, need no
 * font download, and stay crisp at every size.
 *
 * Writes lib/monogram-geometry.ts and app/icon.svg. Re-run with `npm run assets`.
 *
 * Font: Danfo (SIL Open Font License) — vendor/fonts/Danfo[ELSH].ttf,
 * licence text alongside it in vendor/fonts/Danfo-OFL.txt.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import opentype from "opentype.js";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const TILE = 64; // viewBox is 0 0 64 64
const PADDING = 6; // breathing room inside the tile
const TEXT = "ZA";
/* Danfo's ELSH ("Element Shape") axis: 0 Regular, 50 Comb, 100 Claw. Regular
   keeps the fewest fiddly details, which is what survives a 16px favicon. */
const ELSH = 0;
/* Danfo forms each letter as a counter knocked out of a solid slab, so without a
   little tracking the Z and A slabs fuse into one shape at small sizes. */
const TRACKING = 45; // 1/1000 em

const font = opentype.parse(
  readFileSync(resolve(root, "vendor/fonts/Danfo[ELSH].ttf")).buffer,
);

// Rendered at a large size first, then scaled down, so rounding the final
// coordinates to 3dp costs no visible precision.
font.variation.set({ ELSH });

const path = font.getPath(TEXT, 0, 0, 1000, { tracking: TRACKING });
const box = path.getBoundingBox();
const glyphWidth = box.x2 - box.x1;
const glyphHeight = box.y2 - box.y1;

const inner = TILE - PADDING * 2;
const scale = Math.min(inner / glyphWidth, inner / glyphHeight);

// Centre the inked area — not the advance box — so the mark looks optically
// centred rather than mathematically centred.
const tx = (TILE - glyphWidth * scale) / 2 - box.x1 * scale;
const ty = (TILE - glyphHeight * scale) / 2 - box.y1 * scale;

const round = (n) => Number(n.toFixed(3));

/* Apply the transform to the coordinates directly, so consumers only ever deal
   with a single `d` string and cannot get the transform order wrong. */
const commands = path.commands.map((cmd) => {
  const out = { type: cmd.type };
  for (const [axis, offset, s] of [
    ["x", tx, scale],
    ["y", ty, scale],
  ]) {
    for (const key of [axis, `${axis}1`, `${axis}2`]) {
      if (cmd[key] !== undefined) out[key] = round(cmd[key] * s + offset);
    }
  }
  return out;
});

const d = commands
  .map((c) => {
    switch (c.type) {
      case "M":
        return `M${c.x} ${c.y}`;
      case "L":
        return `L${c.x} ${c.y}`;
      case "C":
        return `C${c.x1} ${c.y1} ${c.x2} ${c.y2} ${c.x} ${c.y}`;
      case "Q":
        return `Q${c.x1} ${c.y1} ${c.x} ${c.y}`;
      case "Z":
        return "Z";
      default:
        throw new Error(`Unhandled path command: ${c.type}`);
    }
  })
  .join("");

writeFileSync(
  resolve(root, "lib/monogram-geometry.ts"),
  `/* GENERATED by scripts/generate-monogram.mjs — do not edit by hand.
   The ZA monogram, drawn from the Danfo typeface (SIL OFL) and flattened to
   path data so it renders without a webfont. Run \`npm run assets\` to rebuild. */

export const MONOGRAM_VIEWBOX = "0 0 ${TILE} ${TILE}";

export const MONOGRAM_PATH =
  "${d}";
`,
  "utf8",
);

writeFileSync(
  resolve(root, "app/icon.svg"),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${TILE} ${TILE}" width="${TILE}" height="${TILE}">
  <rect width="${TILE}" height="${TILE}" rx="14" fill="#2d5a3d"/>
  <path d="${d}" fill="#fafaf5"/>
</svg>
`,
  "utf8",
);

console.log(
  `wrote lib/monogram-geometry.ts and app/icon.svg (${commands.length} path commands)`,
);
